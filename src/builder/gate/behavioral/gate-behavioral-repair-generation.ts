import type { BehavioralFailureAttribution } from "./behavioral-failure-attribution.ts";

export interface HandlerRepair extends BehavioralHandlerRepair {
  readonly content: string;
}

export interface RepairRound {
  readonly repaired: readonly HandlerRepair[];
  readonly durationMs: number;
  readonly usage: TokenUsage;
  readonly generations: readonly BehavioralHandlerGenerationAttempt[];
  readonly rejected: readonly string[];
}

export interface RepairRoundInput {
  readonly provider: Provider;
  readonly input: CapabilityGateInput;
  readonly attribution: BehavioralFailureAttribution;
  readonly handlersToRepair: readonly HandlerUnitName[];
  readonly failure: string;
  readonly dependencyCatalog: readonly CapabilityRow[];
  readonly handlers: Readonly<Partial<Record<HandlerUnitName, string>>>;
  readonly generationAttempts: Map<HandlerUnitName, number>;
  readonly maxRepairAttempts: number;
}

/**
 * Rewrite every Handler attribution names while charging each provider call only to that
 * Handler. Conservative rounds skip exhausted units without consuming another unit's budget.
 */
export async function repairAttributedHandlers(options: RepairRoundInput): Promise<RepairRound> {
  const startedAt = performance.now();
  const repaired: HandlerRepair[] = [];
  const rejected: string[] = [];
  const usages: TokenUsage[] = [];
  const generations: BehavioralHandlerGenerationAttempt[] = [];
  const message = repairInstruction(options.attribution, options.failure);

  for (const action of options.attribution.handlers) {
    if (!options.handlersToRepair.includes(action)) {
      rejected.push(`${action} exhausted its per-Handler repair budget`);
      continue;
    }
    const result = await repairOneHandler(options, action, message);
    if (result.repair) repaired.push(result.repair);
    rejected.push(...result.rejected);
    usages.push(...result.usages);
    generations.push(...result.generations);
  }

  return {
    repaired,
    rejected,
    durationMs: performance.now() - startedAt,
    usage: sumUsage(usages),
    generations,
  };
}

interface OneHandlerRepairResult {
  readonly repair?: HandlerRepair;
  readonly rejected: readonly string[];
  readonly usages: readonly TokenUsage[];
  readonly generations: readonly BehavioralHandlerGenerationAttempt[];
}

async function repairOneHandler(
  options: RepairRoundInput,
  action: HandlerUnitName,
  behavioralFailure: string,
): Promise<OneHandlerRepairResult> {
  const unit = { kind: "handler" as const, name: action };
  const rejected: string[] = [];
  const usages: TokenUsage[] = [];
  const generations: BehavioralHandlerGenerationAttempt[] = [];
  let previousFailure: UnitGenerationFailure = { ...unit, message: behavioralFailure };

  while (generationCount(options, action) < options.maxRepairAttempts) {
    const attempt = generationCount(options, action) + 1;
    options.generationAttempts.set(action, attempt);
    const generation = await generateHandlerCandidate(options, action, attempt, previousFailure);
    generations.push(generation.evidence);
    if (generation.kind === "provider_error") {
      appendUsage(usages, generation.usage);
      rejected.push(`${action} could not be regenerated: ${generation.error}`);
      break;
    }
    const { generated } = generation;
    usages.push(generated.usage);
    const staticFailure = checkGeneratedUnit(
      options.input.spec,
      unit,
      generated.content,
      options.dependencyCatalog,
    );
    if (staticFailure) {
      generation.evidence.outcome = "structural_rejected";
      generation.evidence.error = staticFailure.message;
      rejected.push(`${action} failed structural validation: ${staticFailure.message}`);
      previousFailure = {
        ...unit,
        message: `${behavioralFailure} The previous repair failed structural validation: ${staticFailure.message}`,
      };
      continue;
    }
    if (generated.content === options.handlers[action]) {
      generation.evidence.outcome = "byte_identical";
      rejected.push(`${action} regenerated byte-identically and was left alone`);
      break;
    }
    const repair = {
      action,
      content: generated.content,
      durationMs: generated.durationMs,
      usage: generated.usage,
    };
    return { repair, rejected, usages, generations };
  }

  return { rejected, usages, generations };
}

function generationCount(options: RepairRoundInput, action: HandlerUnitName): number {
  return options.generationAttempts.get(action) ?? 0;
}

function appendUsage(usages: TokenUsage[], usage: TokenUsage | undefined): void {
  if (usage) usages.push(usage);
}

type MutableGenerationEvidence = {
  -readonly [Key in keyof BehavioralHandlerGenerationAttempt]: BehavioralHandlerGenerationAttempt[Key];
};

type HandlerCandidateResult =
  | {
      readonly kind: "generated";
      readonly generated: Awaited<ReturnType<typeof generateUnitContent>>;
      readonly evidence: MutableGenerationEvidence;
    }
  | {
      readonly kind: "provider_error";
      readonly error: string;
      readonly usage?: TokenUsage;
      readonly evidence: MutableGenerationEvidence;
    };

async function generateHandlerCandidate(
  options: RepairRoundInput,
  action: HandlerUnitName,
  attempt: number,
  previousFailure: UnitGenerationFailure,
): Promise<HandlerCandidateResult> {
  const startedAt = performance.now();
  try {
    const generated = await generateUnitContent(
      options.provider,
      options.input.spec,
      { kind: "handler", name: action },
      previousFailure,
      options.dependencyCatalog,
    );
    return {
      kind: "generated",
      generated,
      evidence: {
        action,
        attempt,
        durationMs: generated.durationMs,
        outcome: "repaired",
        usage: generated.usage,
      },
    };
  } catch (error) {
    if (isProviderAbortError(error)) throw error;
    const failure = generationFailureEvidence(error, startedAt);
    return {
      kind: "provider_error",
      error: failure.message,
      ...(failure.usage ? { usage: failure.usage } : {}),
      evidence: {
        action,
        attempt,
        durationMs: failure.durationMs,
        outcome: "provider_error",
        ...(failure.usage ? { usage: failure.usage } : {}),
        error: failure.message,
      },
    };
  }
}

function generationFailureEvidence(error: unknown, startedAt: number) {
  const passFailure = error instanceof UnitGenerationPassError ? error : undefined;
  return {
    message: errorMessage(error),
    durationMs: passFailure?.durationMs ?? performance.now() - startedAt,
    usage: passFailure?.usage,
  };
}

function repairInstruction(attribution: BehavioralFailureAttribution, failure: string): string {
  const preamble = attribution.total
    ? "A frozen behavioral test failed against this Handler."
    : `A frozen behavioral test failed and could not be attributed to one Handler (${attribution.reason}); every declared Handler is being rewritten conservatively, so this one may already be correct.`;
  return `${preamble} The test is frozen behavioral intent and cannot change: rewrite the Handler so it satisfies the assertion exactly as written. ${failure}`;
}

function sumUsage(usages: readonly TokenUsage[]): TokenUsage {
  return {
    inputTokens: sumDefined(usages.map((usage) => usage.inputTokens)),
    outputTokens: sumDefined(usages.map((usage) => usage.outputTokens)),
    totalTokens: sumDefined(usages.map((usage) => usage.totalTokens)),
  };
}

function sumDefined(values: readonly (number | undefined)[]): number | undefined {
  const present = values.filter((value): value is number => value !== undefined);
  return present.length === 0 ? undefined : present.reduce((sum, value) => sum + value, 0);
}
